import json
import uuid
from google import genai
from google.cloud import storage
from google.genai import types
from google.adk.tools import ToolContext

# Hardcoded GCP Project ID and Cloud Storage Bucket name as requested
PROJECT_ID = "qwiklabs-gcp-03-fcbe5502dab4"
BUCKET_NAME = "apex-coach-media-qwiklabs-gcp-03-fcbe5502dab4"


async def generate_fitness_image(prompt: str, tool_context: ToolContext) -> str:
    """Generates an image for athletic gear, workout routines, or motivational visual previews in the fitness domain.

    Args:
        prompt: Detailed description of the image to generate (e.g. 'A sleek carbon-fiber trail running shoe on a mountain path').
        tool_context: ADK ToolContext instance for saving session artifacts.

    Returns:
        A JSON string containing the public Cloud Storage URL and artifact details.
    """
    try:
        # 1. Initialize Gemini client with Vertex AI in global region
        client = genai.Client(vertexai=True, project=PROJECT_ID, location="global")
        response = client.models.generate_content(
            model="gemini-3.1-flash-lite-image",
            contents=prompt,
            config=types.GenerateContentConfig(
                response_modalities=["IMAGE"],
            ),
        )

        if not response.candidates or not response.candidates[0].content.parts:
            return json.dumps({"error": "No image generated by the model."})

        part = response.candidates[0].content.parts[0]
        if not part.inline_data or not part.inline_data.data:
            return json.dumps({"error": "Generated image inline data is empty."})

        image_bytes = part.inline_data.data
        mime_type = part.inline_data.mime_type or "image/jpeg"
        extension = "jpg" if "jpeg" in mime_type or "jpg" in mime_type else "png"

        image_id = uuid.uuid4().hex[:8]
        filename = f"fitness_image_{image_id}.{extension}"

        # 2. Save artifact using tool_context.save_artifact for Playground Artifacts panel
        artifact_part = types.Part.from_bytes(data=image_bytes, mime_type=mime_type)
        await tool_context.save_artifact(filename=filename, artifact=artifact_part)

        # 3. Upload image bytes directly to public GCS bucket (without writing to a local file)
        storage_client = storage.Client(project=PROJECT_ID)
        bucket = storage_client.bucket(BUCKET_NAME)
        blob = bucket.blob(filename)
        blob.upload_from_string(image_bytes, content_type=mime_type)

        public_url = f"https://storage.googleapis.com/{BUCKET_NAME}/{filename}"

        return json.dumps(
            {
                "status": "success",
                "prompt": prompt,
                "image_url": public_url,
                "artifact_filename": filename,
            },
            indent=2,
        )
    except Exception as e:
        return json.dumps({"error": f"Failed to generate image: {str(e)}"})


async def generate_fitness_video(prompt: str, tool_context: ToolContext) -> str:
    """Generates a short video for athletic gear, workout demonstrations, or athletic scenes in the fitness domain using Google's Omni model (gemini-omni-flash-preview).

    Args:
        prompt: Detailed description of the video to generate (e.g. 'A short video of a runner sprinting on a track').
        tool_context: ADK ToolContext instance for saving session artifacts.

    Returns:
        A JSON string containing the public Cloud Storage URL and artifact details.
    """
    try:
        # 1. Initialize Gemini client with Vertex AI in global region
        client = genai.Client(vertexai=True, project=PROJECT_ID, location="global")

        # 2. Use Interactions API with gemini-omni-flash-preview
        interaction = client.interactions.create(
            model="gemini-omni-flash-preview",
            input=prompt,
            generation_config={"response_modalities": ["VIDEO"]},
        )

        vid = interaction.output_video
        if not vid or not vid.data:
            return json.dumps({"error": "No video generated by the model."})

        video_bytes = vid.data
        mime_type = getattr(vid, "mime_type", None) or "video/mp4"
        extension = "mp4"

        video_id = uuid.uuid4().hex[:8]
        filename = f"fitness_video_{video_id}.{extension}"

        # 3. Save artifact using tool_context.save_artifact for Playground Artifacts panel
        artifact_part = types.Part.from_bytes(data=video_bytes, mime_type=mime_type)
        await tool_context.save_artifact(filename=filename, artifact=artifact_part)

        # 4. Upload video bytes directly to public GCS bucket (without writing to a local file)
        storage_client = storage.Client(project=PROJECT_ID)
        bucket = storage_client.bucket(BUCKET_NAME)
        blob = bucket.blob(filename)
        blob.upload_from_string(video_bytes, content_type=mime_type)

        public_url = f"https://storage.googleapis.com/{BUCKET_NAME}/{filename}"

        return json.dumps(
            {
                "status": "success",
                "prompt": prompt,
                "video_url": public_url,
                "artifact_filename": filename,
            },
            indent=2,
        )
    except Exception as e:
        return json.dumps({"error": f"Failed to generate video: {str(e)}"})
